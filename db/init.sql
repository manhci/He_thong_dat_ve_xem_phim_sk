-- Drop tables if exists in reverse dependency order
DROP TABLE IF EXISTS booking_seats CASCADE;
DROP TABLE IF EXISTS bookings CASCADE;
DROP TABLE IF EXISTS showtimes CASCADE;
DROP TABLE IF EXISTS events CASCADE;
DROP TABLE IF EXISTS venues CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- 1. USERS TABLE
CREATE TABLE users (
    id SERIAL PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('customer', 'staff', 'admin')),
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. CATEGORIES TABLE
CREATE TABLE categories (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) UNIQUE NOT NULL,
    sort_order INT DEFAULT 0
);

-- 3. VENUES TABLE
CREATE TABLE venues (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) UNIQUE NOT NULL,
    address VARCHAR(255) NOT NULL,
    rows_count INT NOT NULL CHECK (rows_count > 0),
    seats_per_row INT NOT NULL CHECK (seats_per_row > 0),
    vip_rows INT DEFAULT 0 CHECK (vip_rows >= 0 AND vip_rows <= rows_count),
    capacity INT NOT NULL CHECK (capacity > 0)
);

-- 4. EVENTS TABLE (Movies & Events)
CREATE TABLE events (
    id SERIAL PRIMARY KEY,
    category_id INT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    type VARCHAR(20) NOT NULL CHECK (type IN ('movie', 'event')),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    poster_path VARCHAR(255),
    duration_minutes INT NOT NULL CHECK (duration_minutes > 0),
    age_rating VARCHAR(10) NOT NULL CHECK (age_rating IN ('P', 'K', 'T13', 'T16', 'T18')),
    language VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('draft', 'published', 'cancelled', 'completed')),
    created_by INT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. SHOWTIMES TABLE
CREATE TABLE showtimes (
    id SERIAL PRIMARY KEY,
    event_id INT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    venue_id INT NOT NULL REFERENCES venues(id) ON DELETE RESTRICT,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    price_standard NUMERIC(12,0) NOT NULL CHECK (price_standard >= 0),
    price_vip NUMERIC(12,0) NOT NULL CHECK (price_vip >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('scheduled', 'cancelled', 'completed')),
    CHECK (ends_at > starts_at)
);

CREATE INDEX idx_showtimes_event_starts ON showtimes (event_id, starts_at);
CREATE INDEX idx_showtimes_venue_starts ON showtimes (venue_id, starts_at);

-- 6. BOOKINGS TABLE
CREATE TABLE bookings (
    id SERIAL PRIMARY KEY,
    booking_code VARCHAR(50) UNIQUE NOT NULL,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    showtime_id INT NOT NULL REFERENCES showtimes(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL CHECK (status IN ('pending', 'confirmed', 'checked_in', 'cancelled', 'expired')),
    total_amount NUMERIC(12,0) NOT NULL,
    payment_method VARCHAR(20) CHECK (payment_method IN ('cash', 'card', 'qr')),
    amount_paid NUMERIC(12,0) DEFAULT 0,
    change_amount NUMERIC(12,0) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    expires_at TIMESTAMPTZ,
    paid_at TIMESTAMPTZ,
    checked_in_at TIMESTAMPTZ,
    checked_in_by INT REFERENCES users(id)
);

CREATE INDEX idx_bookings_user ON bookings (user_id);
CREATE INDEX idx_bookings_showtime ON bookings (showtime_id);
CREATE INDEX idx_bookings_code ON bookings (booking_code);

-- 7. BOOKING_SEATS TABLE
CREATE TABLE booking_seats (
    id SERIAL PRIMARY KEY,
    booking_id INT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    showtime_id INT NOT NULL REFERENCES showtimes(id) ON DELETE RESTRICT,
    seat_label VARCHAR(10) NOT NULL,
    seat_class VARCHAR(20) NOT NULL CHECK (seat_class IN ('standard', 'vip')),
    price NUMERIC(12,0) NOT NULL CHECK (price >= 0),
    is_active BOOLEAN DEFAULT true
);

-- PARTIAL UNIQUE INDEX: Automatically prevent double booking on active seats
CREATE UNIQUE INDEX idx_booking_seats_active ON booking_seats (showtime_id, seat_label) WHERE is_active = true;

